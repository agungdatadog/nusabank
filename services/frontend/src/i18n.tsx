export type Lang = "id" | "en";
const MESSAGES: Record<Lang, Record<MessageKey, string>> = { id, en };
const LANG_KEY = "nusabank.lang";

// Storage can throw (private mode, blocked site data); Indonesian is the default either way,
// which also keeps the Synthetics browser tests on the Indonesian copy they assert.
function storedLang(): Lang {
  try {
    return localStorage.getItem(LANG_KEY) === "en" ? "en" : "id";
  } catch {
    return "id";
  }
}

let current: Lang = storedLang();

function format(lang: Lang, key: MessageKey, vars?: Record<string, string | number>) {
  const text = MESSAGES[lang][key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : text;
}

/** For code outside React (the API client's fallback error). */
export const translate = (key: MessageKey, vars?: Record<string, string | number>) => format(current, key, vars);

/**
 * RUM names clicks after the element's text, so the same button would be two actions in
 * two languages. Pin the name to the Indonesian copy, which is what RUM history already has.
 */
export const actionName = (key: MessageKey) => ({ "data-dd-action-name": id[key] });

interface LangState {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
}

const LangContext = createContext<LangState | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(current);

  useEffect(() => {
    current = lang;
    document.documentElement.lang = lang;
    rumSetLang(lang);
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch {
      /* preference just won't persist */
    }
    setLangState(next);
  }, []);

  const t = useCallback((key: MessageKey, vars?: Record<string, string | number>) => format(lang, key, vars), [lang]);

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export function useT() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useT outside LangProvider");
  return ctx;
}
